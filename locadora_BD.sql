CREATE DATABASE LOCADORA;

USE LOCADORA;

CREATE TABLE MIDIA (
IN_MIDIA INT PRIMARY KEY NOT NULL,
TIPO_MIDIA VARCHAR(45)
);

CREATE TABLE GENERO (
ID_GENERO INT PRIMARY KEY NOT NULL,
DESCRICAO_GENERO VARCHAR (45)
);

CREATE TABLE FAIXA_ETARIA(
ID_FAIXA_ETARIA INT PRIMARY KEY NOT NULL,
DESCRICAO_FAIXA_ETARIA VARCHAR(45)
);

CREATE TABLE FILME(
ID_FILME INT PRIMARY KEY NOT NULL,
NOME_FILME VARCHAR (45),
ANO_LANCAMENTO_FILME INT,
DURACAO_FILME INT,
VALOR_DIARIA_FILME DOUBLE,
VALOR_VENDA_FILME DOUBLE,
ID_MIDIA INT NOT NULL,
ID_GENERO INT NOT NULL,
ID_FAIXA_ETARIA INT NOT NULL,
FOREIGN KEY (ID_MIDIA) REFERENCES MIDIA (ID_MIDIA),
FOREIGN KEY (ID_GENERO) REFERENCES GENERO (ID_GENERO),
FOREIGN KEY (ID_FAIXA_ETARIA) REFERENCES FAIXA_ETARIA (ID_FAIXA_ETARIA)
);

